import { expect, test, type Page } from '@playwright/test'
async function analyze(page: Page) {
  await page.goto('/#text')
  await page.getByRole('textbox', { name: '문자 내용' }).fill('은행입니다. 인증번호를 알려주세요.')
  await page.getByRole('button', { name: '분석하기', exact: true }).click()
  await page.getByRole('button', { name: '가족에게 공유', exact: true }).click()
}
test('링크 공유 화면과 표기 없는 상태 미리보기', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await analyze(page)
  await expect(page.getByRole('checkbox', { name: '동생에게 공유' })).toBeDisabled()
  const heights = await page.locator('.family-share-recipient').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().height))
  expect(Math.abs(heights[0] - heights[1])).toBeLessThan(1)
  await expect(page.getByText('대응 방법 보기', { exact: true })).toHaveCount(0)
  await expect(page.getByText('공유할 내용 선택', { exact: true })).toHaveCount(0)
  await page.screenshot({ path: 'test-results/share-selection.png', fullPage: true, style: '.family-dev-panel { display:none !important; }' })
  await page.getByRole('button', { name: '공유하기', exact: true }).click()
  await expect(page.getByText('공유할 텍스트 확인', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: '공유할 내용' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '공유할 앱 선택' })).toBeDisabled()
  await expect(page.getByRole('button', { name: '링크 복사하기' })).toBeDisabled()
  await page.screenshot({ path: 'test-results/share-methods.png', fullPage: false })
  await page.getByRole('button', { name: '모의 공유 상태 보기' }).click()
  await expect(page.getByText('모의 공유 상태', { exact: true })).toHaveCount(0)
  await expect(page.locator('.family-share-main')).not.toContainText('(예시)')
  await page.screenshot({ path: 'test-results/share-status.png', fullPage: true, style: '.family-dev-panel { display:none !important; }' })
  await page.getByText('공유 상태 미리보기', { exact: true }).click()
  await page.getByRole('button', { name: '가족 확인 상태 보기' }).click()
  await expect(page.getByText('우리딸♥ 님이 확인했어요', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '의견 도착 상태 보기' }).click()
  await expect(page.locator('.family-share-main')).not.toContainText('(예시)')
})
test('가족 미선택 시 공유 불가, 좁은 화면·큰 글씨에서도 가족 카드 높이가 같다', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 }); await analyze(page)
  await page.getByRole('checkbox', { name: '우리딸♥에게 공유' }).uncheck()
  await expect(page.getByRole('button', { name: '공유하기', exact: true })).toBeDisabled()
  await page.getByRole('checkbox', { name: '우리딸♥에게 공유' }).check()
  await page.locator('.app-shell').evaluate(el => el.classList.add('large-text'))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const heights = await page.locator('.family-share-recipient').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().height))
  expect(Math.abs(heights[0] - heights[1])).toBeLessThan(1)
  await page.getByRole('button', { name: '공유하기', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '공유하기', exact: true })).toBeFocused()
})
