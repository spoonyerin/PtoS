import { expect, test, type Page } from '@playwright/test'
async function openFamily(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: '가족 보호', exact: true }).click()
}
async function openAuto(page: Page) {
  await page.getByRole('button', { name: /위험 메시지 자동 알림/ }).click()
}

test('가족 보호 → 자동 알림 OFF/ON → 수신자 변경과 삭제 시 재동의', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await openFamily(page)
  await expect(page.getByRole('heading', { name: '가족 보호', exact: true })).toBeVisible()
  await expect(page.getByText('수락 대기', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/family-overview.png', fullPage: true })
  await openAuto(page)
  await expect(page.locator('.auto-state')).toHaveText('OFF')
  await page.screenshot({ path: 'test-results/family-alert-off.png', fullPage: true })
  await page.getByRole('button', { name: '＋ 가족 추가하기', exact: true }).click()
  await expect(page.getByRole('heading', { name: '가족 연결하기', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '가족 보호로 돌아가기' }).click()
  await openAuto(page)
  await expect(page.locator('.auto-state')).toHaveText('OFF')
  await page.getByRole('button', { name: '동의하고 자동 알림 켜기' }).click()
  await expect(page.locator('.auto-state')).toHaveText('ON')
  await page.screenshot({ path: 'test-results/family-alert-on.png', fullPage: true })
  await page.getByRole('button', { name: '＋ 가족 추가하기', exact: true }).click()
  await expect(page.getByRole('heading', { name: '가족 연결하기', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '가족 보호로 돌아가기' }).click()
  await openAuto(page)
  await expect(page.locator('.auto-state')).toHaveText('ON')
  await page.getByRole('button', { name: '바꾸기', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('button', { name: /동생/ })).toBeDisabled()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '가족 보호로 돌아가기' }).click()
  await page.getByRole('button', { name: '수정하기' }).click()
  await page.getByRole('button', { name: '모의 수락' }).click()
  await page.getByRole('button', { name: '수정 완료' }).click()
  await openAuto(page)
  await expect(page.locator('.auto-state')).toHaveText('ON')
  await page.getByRole('button', { name: '바꾸기', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: /동생/ }).click()
  await expect(page.locator('.auto-state')).toHaveText('OFF')
  await page.getByRole('button', { name: '동의하고 자동 알림 켜기' }).click()
  await page.getByRole('button', { name: '가족 보호로 돌아가기' }).click()
  await page.getByRole('button', { name: '수정하기' }).click()
  await page.getByRole('button', { name: '동생 삭제', exact: true }).click()
  await page.getByRole('button', { name: '수정 완료' }).click()
  await openAuto(page)
  await expect(page.locator('.auto-state')).toHaveText('OFF')
  await expect(page.getByRole('button', { name: '동의하고 자동 알림 켜기' })).toBeDisabled()
})

test('가족 연결: 번호 오류·예시 연락처·초대 대기, 실제 전송·저장 없음', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await openFamily(page)
  const posts: string[] = []
  page.on('request', request => { if(request.method() === 'POST') posts.push(request.url()) })
  await page.getByRole('button', { name: '＋ 가족 더 연결하기', exact: true }).click()
  await page.screenshot({ path: 'test-results/family-connect-empty.png', fullPage: true })
  await page.getByRole('button', { name: '초대 보내기' }).click()
  await expect(page.getByRole('alert')).toContainText('휴대전화 번호')
  await expect(page.getByRole('textbox', { name: '연락처', exact: true })).toBeFocused()
  await page.getByRole('radio', { name: '배우자', exact: true }).check()
  await page.getByRole('button', { name: '연락처에서 고르기' }).click()
  await expect(page.getByRole('dialog')).toContainText('실제 연락처에는 접근하지 않아요')
  await page.getByRole('button', { name: /우리 아들♥/ }).click()
  await page.getByRole('radio', { name: '자식', exact: true }).check()
  await page.screenshot({ path: 'test-results/family-connect-selected.png', fullPage: true })
  await page.getByRole('button', { name: '다시 고르기' }).click()
  await page.getByRole('button', { name: '전화번호 직접 입력', exact: true }).click()
  await page.getByRole('textbox', { name: '연락처', exact: true }).fill('010-0000-0000')
  await page.getByRole('button', { name: '초대 보내기' }).click()
  await expect(page.getByRole('heading', { name: '가족 보호', exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('실제 메시지는 보내지 않았으며')
  expect(posts).toEqual([])
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])
  await page.getByRole('button', { name: /가족 보호 기록/ }).click()
  await expect(page.getByText('아직 보호 기록이 없어요.')).toBeVisible()
  await page.getByRole('button', { name: '가족 보호로 돌아가기' }).click()
  await page.getByRole('button', { name: /긴급 연락/ }).click()
  await page.getByRole('button', { name: /우리딸♥/ }).click()
  await expect(page.getByRole('status')).toContainText('실제 전화는 걸리지 않습니다')
})

