import { expect, test } from '@playwright/test'

test('공식 확인 가이드 검색·분야·택배사·우체국 상세와 고정 공식 링크', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '가족 보호', exact: true }).click()
  await page.getByRole('button', { name: /공식 확인 가이드/ }).click()
  await page.screenshot({ path: 'test-results/guide-categories.png', fullPage: true, style: '.family-dev-panel{display:none!important}' })
  await page.getByRole('textbox', { name: '기관·은행·택배사 검색하기' }).fill('우체국')
  await expect(page.locator('.guide-category-grid button')).toHaveCount(1)
  await page.getByRole('button', { name: /택배사·우체국/ }).click()
  await expect(page.locator('.guide-carriers button')).toHaveCount(8)
  await page.screenshot({ path: 'test-results/guide-carriers.png', fullPage: true, style: '.family-dev-panel{display:none!important}' })
  await page.getByRole('button', { name: '우체국 택배', exact: true }).click()
  await expect(page.getByRole('link', { name: /인터넷우체국 배송조회/ })).toHaveAttribute('href', 'https://www.epost.go.kr/')
  await expect(page.getByRole('link', { name: /우편고객센터/ })).toHaveAttribute('href', 'tel:15881300')
  await page.screenshot({ path: 'test-results/guide-post-office.png', fullPage: true, style: '.family-dev-panel{display:none!important}' })
  await page.setViewportSize({ width: 320, height: 640 })
  await page.locator('.app-shell').evaluate(el => el.classList.add('large-text'))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('개발 패널 관점 선택·기록 탭·받은 요청 의견과 전송 팝업·기록 반영', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const writes: string[] = []
  page.on('request', request => { if (request.method() !== 'GET') writes.push(request.url()) })
  await page.getByText('개발용 미리보기', { exact: true }).click()
  await page.getByRole('combobox', { name: '가족 보호 기록 관점', exact: true }).selectOption('sent')
  await page.getByRole('button', { name: '가족 보호 기록 보기', exact: true }).click()
  await expect(page.getByRole('tab', { name: '보낸 요청', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.screenshot({ path: 'test-results/history-sent.png', fullPage: true, style: '.family-dev-panel{display:none!important}' })
  await page.getByRole('combobox', { name: '가족 보호 기록 관점', exact: true }).selectOption('received')
  await expect(page.getByRole('tab', { name: '받은 요청', exact: true })).toHaveAttribute('aria-selected', 'true')
  const replies = page.locator('.history-my-reply')
  await expect(replies.first().locator('.history-my-reply-text')).toBeEmpty()
  await expect(replies.nth(1).locator('.history-my-reply-text')).toHaveText('엄마 내가 곧 전화할게')
  for (const row of await replies.all()) {
    const plane = await row.locator('.history-plane').boundingBox()
    const author = await row.locator('strong').boundingBox()
    expect(plane!.width).toBeLessThanOrEqual(26)
    expect(author!.x - plane!.x - plane!.width).toBeGreaterThan(8)
    expect(author!.x - plane!.x - plane!.width).toBeLessThan(16)
  }
  await page.screenshot({ path: 'test-results/history-received.png', fullPage: true, style: '.family-dev-panel{display:none!important}' })
  await page.getByText('개발용 미리보기', { exact: true }).click()
  await page.getByRole('button', { name: '택배 주소 재입력 요청 확인하기', exact: true }).click()
  await page.getByRole('radio', { name: '직접 입력하기', exact: true }).check()
  await page.getByRole('textbox', { name: '보낼 확인 메시지' }).fill('엄마 제가 공식 앱으로 확인해 볼게요.')
  await page.getByRole('button', { name: '의견 보내기', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '의견 보내기' })).toBeVisible()
  await page.screenshot({ path: 'test-results/opinion-confirmation.png', fullPage: false })
  await page.getByRole('button', { name: '확인', exact: true }).click()
  await expect(page.getByRole('button', { name: '의견 보냄' })).toBeDisabled()
  await page.screenshot({ path: 'test-results/opinion-completed.png', fullPage: true, style: '.family-dev-panel{display:none!important}' })
  await page.getByRole('button', { name: '가족 보호 기록 보기', exact: true }).click()
  await expect(page.locator('.history-my-reply-text').first()).toHaveText('엄마 제가 공식 앱으로 확인해 볼게요.')
  expect(writes).toEqual([])
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])
  await page.setViewportSize({ width: 320, height: 640 })
  await page.locator('.app-shell').evaluate(el => el.classList.add('large-text'))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
